export const courses = catalogue.map(course=>({
  ...course,
  parts:course.parts.map((part,partIndex)=>{
    let number=0;
    return {...part,groups:part.groups.map(group=>({
      ...group,
      topics:group.topics.trim().split('\n').map(title=>({number:`${partIndex+1}.${++number}`,title})),
    }))};
  }),
}));
export const topicCount = course=>course.parts.reduce((total,part)=>total+part.groups.reduce((sum,group)=>sum+group.topics.length,0),0);
export const word = (count,forms)=>forms[count%100>=11&&count%100<=14?2:count%10===1?0:count%10>=2&&count%10<=4?1:2];
export const topicText = count=>`${count} ${word(count,['тема','темы','тем'])}`;
